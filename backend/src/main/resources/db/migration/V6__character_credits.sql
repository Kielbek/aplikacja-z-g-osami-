-- Jednorazowe pakiety znaków kupowane bez subskrypcji.
-- Zakupy są zapisem rozliczeniowym: bez klucza obcego, aby przetrwały usunięcie konta (obowiązki księgowe).
create table character_credits (
    id           bigint generated by default as identity primary key,
    user_id      varchar(255) not null,
    pack_id      varchar(32)  not null,
    characters   bigint       not null,
    amount_minor integer      not null,
    currency     varchar(8)   not null,
    source       varchar(16)  not null,
    reference    varchar(255) unique,
    created_at   timestamp(6) with time zone not null
);
create index idx_credits_user on character_credits (user_id);

-- Część zdarzenia zużycia pokryta znakami z pakietów (reszta liczy się do limitu planu).
alter table usage_events add column credit_characters integer not null default 0;
