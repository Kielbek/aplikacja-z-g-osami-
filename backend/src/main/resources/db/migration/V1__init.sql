-- VoiceCraft AI — schemat początkowy.
-- Zgodny z PostgreSQL 14+ oraz H2 (tryb PostgreSQL, środowisko deweloperskie).
-- Wygenerowany z encji JPA i uzupełniony o klucze obce oraz indeksy.

create table users (
    id                varchar(255) not null primary key,
    email             varchar(255) not null unique,
    password_hash     varchar(255),
    full_name         varchar(255),
    google_sub        varchar(255) unique,
    picture_url       varchar(255),
    token_version     integer      not null,
    created_at        timestamp(6) with time zone,
    last_login_at     timestamp(6) with time zone
);

create table accounts (
    user_id                   varchar(255) not null primary key references users (id),
    full_name                 varchar(255),
    email                     varchar(255),
    company                   varchar(255),
    role                      varchar(255),
    plan_id                   varchar(255) check (plan_id in ('FREE', 'STARTER', 'PRO', 'BUSINESS')),
    stripe_customer_id        varchar(255),
    stripe_subscription_id    varchar(255),
    subscription_status       varchar(255),
    billing_period_start      date,
    renews_on                 date,
    export_format             varchar(255),
    mp3_bitrate               integer      not null,
    pause_between_segments_ms integer      not null,
    file_name_pattern         varchar(255),
    theme                     varchar(255),
    default_language          varchar(255),
    default_voice_id          varchar(255),
    auto_split_on_paste       boolean      not null,
    confirm_before_delete     boolean      not null,
    play_after_generate       boolean      not null,
    email_notifications       boolean      not null,
    updated_at                timestamp(6) with time zone
);
create index idx_accounts_stripe_customer on accounts (stripe_customer_id);

create table password_reset_tokens (
    token_hash varchar(64)  not null primary key,
    user_id    varchar(255) not null references users (id),
    expires_at timestamp(6) with time zone,
    used_at    timestamp(6) with time zone
);

create table voices (
    id                 varchar(255) not null primary key,
    name               varchar(255) not null,
    kind               varchar(255) check (kind in ('LIBRARY', 'DESIGNED', 'CLONED')),
    owner_id           varchar(255) references users (id),
    gender             varchar(255),
    age                integer,
    languages          varchar(255),
    categories         varchar(255),
    traits             varchar(255),
    description        varchar(1000),
    engine_prompt      varchar(1000),
    reference_id       varchar(255),
    sample_text        varchar(1000),
    sample_file        varchar(255),
    sample_engine_mode varchar(255),
    use_count          integer      not null,
    created_at         timestamp(6) with time zone
);
create index idx_voices_owner on voices (owner_id);

create table voice_favorites (
    id       bigint generated by default as identity primary key,
    user_id  varchar(255) not null references users (id),
    voice_id varchar(255) not null references voices (id),
    unique (user_id, voice_id)
);

create table projects (
    id                  varchar(255) not null primary key,
    owner_id            varchar(255) not null references users (id),
    name                varchar(255) not null,
    created_at          timestamp(6) with time zone,
    updated_at          timestamp(6) with time zone,
    last_generated_at   timestamp(6) with time zone,
    engine              varchar(255),
    language            varchar(255),
    voice_id            varchar(255),
    style               varchar(255),
    emotion             varchar(255),
    speed               float(53),
    expressiveness      float(53),
    cfg_value           float(53),
    inference_timesteps integer,
    normalize           boolean,
    denoise             boolean,
    seed                integer
);
create index idx_projects_owner_updated on projects (owner_id, updated_at);

create table segments (
    id             varchar(255)  not null primary key,
    project_id     varchar(255)  not null references projects (id) on delete cascade,
    position       integer       not null,
    text           varchar(5000) not null,
    audio_file     varchar(255),
    duration_ms    bigint        not null,
    generated_hash varchar(64),
    engine_mode    varchar(255),
    generated_at   timestamp(6) with time zone,
    error          varchar(1000)
);
create index idx_segments_project on segments (project_id, position);

create table generation_history (
    id           bigint generated by default as identity primary key,
    user_id      varchar(255) not null references users (id),
    type         varchar(255),
    project_id   varchar(255),
    project_name varchar(255),
    segment_id   varchar(255),
    voice_id     varchar(255),
    voice_name   varchar(255),
    text_preview varchar(400),
    characters   integer      not null,
    duration_ms  bigint       not null,
    engine_mode  varchar(255),
    status       varchar(255),
    error        varchar(1000),
    audio_file   varchar(255),
    created_at   timestamp(6) with time zone
);
create index idx_history_user_created on generation_history (user_id, created_at);
create index idx_history_user_audio on generation_history (user_id, audio_file);

create table generation_jobs (
    id                 varchar(255) not null primary key,
    user_id            varchar(255) not null references users (id),
    project_id         varchar(255) not null,
    status             varchar(255) not null check (status in ('QUEUED', 'RUNNING', 'DONE', 'CANCELLED', 'FAILED')),
    segment_ids        varchar(20000),
    total              integer      not null,
    done               integer      not null,
    failed             integer      not null,
    current_segment_id varchar(255),
    last_error         varchar(1000),
    last_error_code    varchar(255),
    cancel_requested   boolean      not null,
    created_at         timestamp(6) with time zone,
    started_at         timestamp(6) with time zone,
    finished_at        timestamp(6) with time zone
);
create index idx_jobs_project_status on generation_jobs (project_id, user_id, status);
create index idx_jobs_status on generation_jobs (status);

create table stripe_events (
    id           varchar(255) not null primary key,
    type         varchar(255),
    processed_at timestamp(6) with time zone
);
