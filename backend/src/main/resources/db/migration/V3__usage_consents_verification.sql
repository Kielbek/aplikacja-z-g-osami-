-- Licznik zużycia niezależny od historii, nagrania wzorcowe głosów, rejestr zgód na klonowanie,
-- weryfikacja adresu e-mail i akceptacja regulaminu.

-- 1. Zdarzenia zużycia: użytkownik nie może ich usunąć (czyszczenie historii nie zeruje limitu).
create table usage_events (
    id          bigint generated by default as identity primary key,
    user_id     varchar(255) not null references users (id),
    kind        varchar(32)  not null,
    characters  integer      not null,
    duration_ms bigint       not null,
    created_at  timestamp(6) with time zone not null
);
create index idx_usage_user_created on usage_events (user_id, created_at);

insert into usage_events (user_id, kind, characters, duration_ms, created_at)
select user_id, type, characters, duration_ms, created_at
from generation_history
where status = 'success' and type <> 'export';

-- 2. Nagranie wzorcowe (referencja) głosu przechowywane w magazynie aplikacji.
alter table voices add column reference_file varchar(255);
alter table voices add column reference_text varchar(1000);

-- 3. Rejestr zgód na klonowanie głosu (dowód zgody — zachowywany także po usunięciu głosu).
create table voice_consents (
    id              varchar(255) not null primary key,
    user_id         varchar(255) not null,
    user_email      varchar(255),
    voice_id        varchar(255),
    voice_name      varchar(255),
    reference_id    varchar(255),
    consent_version varchar(32)   not null,
    consent_text    varchar(2000) not null,
    audio_sha256    varchar(64)   not null,
    audio_bytes     bigint        not null,
    file_name       varchar(255),
    ip              varchar(64),
    user_agent      varchar(500),
    created_at      timestamp(6) with time zone not null
);
create index idx_consents_user on voice_consents (user_id);

-- 4. Weryfikacja e-mail i akceptacja regulaminu. Istniejące konta uznajemy za zweryfikowane.
alter table users add column email_verified_at timestamp(6) with time zone;
alter table users add column terms_accepted_at timestamp(6) with time zone;
alter table users add column terms_version varchar(32);
update users set email_verified_at = created_at;

create table email_verification_tokens (
    token_hash varchar(64)  not null primary key,
    user_id    varchar(255) not null references users (id),
    email      varchar(255) not null,
    expires_at timestamp(6) with time zone not null,
    used_at    timestamp(6) with time zone
);
create index idx_email_tokens_user on email_verification_tokens (user_id);
